"""Bundle places.geojson and excursions.csv into map-data.js for map.html.

map.html loads its data from a plain script so it works when opened
directly from disk (file://), where browsers block fetch() of local files.

Usage (from the 2027-ireland directory):
    python3 scripts/build_map_data.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    geojson = json.loads((ROOT / "places.geojson").read_text())
    excursions = {}
    with open(ROOT / "excursions.csv", newline="") as fh:
        for row in csv.DictReader(fh):
            price = row["starting_price_usd"]
            excursions[row["excursion_id"]] = {
                "id": row["excursion_id"],
                "title": row["title"],
                "day": int(row["day"]),
                "port_id": row["port_id"],
                "price": int(price) if price.isdigit() else None,
                "duration": row["duration"],
                "activity_level": row["activity_level"],
                "wheelchair_accessible": row["wheelchair_accessible"],
                "meals": row["meals"],
                "url": row["url"],
                "day_file": row["day_file"],
            }
    data = {"geojson": geojson, "excursions": excursions}
    out = ROOT / "map-data.js"
    out.write_text(
        "// Generated by scripts/build_map_data.py from places.geojson and excursions.csv.\n"
        "// Do not edit by hand; edit those files and re-run the script.\n"
        "window.CRUISE_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
    )
    places = sum(1 for f in geojson["features"] if f["properties"]["kind"] == "place")
    print(f"Wrote {out.name}: {places} places, {len(excursions)} excursions")


if __name__ == "__main__":
    main()
