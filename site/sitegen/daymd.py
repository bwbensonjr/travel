"""Parse the generated day-NN-*.md files.

Expected layout (generated by the itinerary scraper):

    ---                       YAML front matter: day, date, title, stops[]
    ---
    # Day N: ...              ignored (rebuilt from front matter)
    ...                       stop table and links, ignored

  Single-stop day:
    ## About <port>           port description
    ## Shore Excursions (N)   summary table, ignored
    ### <excursion title>     facts table with an "Excursion ID" row, then description

  Multi-stop day (e.g. day 9): the same sections one level deeper, under
    ## <stop name>            one heading per stop, matching front matter stops[].name

Any other section, at any level, is kept as a note so hand-written research
appears on the site. A heading that looks like an excursion but has no
"Excursion ID" row is also treated as a note.
"""
import re
from dataclasses import dataclass, field
from pathlib import Path

import yaml

HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
TABLE_ROW = re.compile(r"^\|\s*(.*?)\s*\|\s*(.*?)\s*\|\s*$")


class DayParseError(ValueError):
    pass


@dataclass
class Excursion:
    id: str
    title: str
    facts: dict
    description_md: str
    line: int


@dataclass
class Stop:
    name: str
    port_id: str
    about_md: str = ""
    excursions: list = field(default_factory=list)


@dataclass
class Note:
    title: str
    body_md: str
    stop: str = ""


@dataclass
class DayDoc:
    path: Path
    front: dict
    stops: list
    notes: list

    @property
    def day(self):
        return int(self.front["day"])

    def excursions(self):
        return [e for s in self.stops for e in s.excursions]


def split_front_matter(text, path):
    if not text.startswith("---\n"):
        raise DayParseError(f"{path}:1: missing YAML front matter")
    end = text.find("\n---\n", 4)
    if end == -1:
        raise DayParseError(f"{path}:1: unterminated YAML front matter")
    front = yaml.safe_load(text[4:end])
    body_start_line = text[: end + 5].count("\n") + 1
    return front, text[end + 5:], body_start_line


def _parse_facts(lines):
    """Split leading table rows from the rest of a section's lines."""
    facts, i = {}, 0
    while i < len(lines) and not lines[i].strip():
        i += 1
    while i < len(lines) and lines[i].lstrip().startswith("|"):
        m = TABLE_ROW.match(lines[i].strip())
        if m:
            key, value = m.group(1), m.group(2)
            if not (key == "Field" and value == "Value") and not set(key) <= set("-: "):
                facts[key] = value
        i += 1
    return facts, "\n".join(lines[i:]).strip()


def parse_day_file(path):
    path = Path(path)
    text = path.read_text()
    front, body, first_line = split_front_matter(text, path)
    if not isinstance(front, dict) or "day" not in front or "stops" not in front:
        raise DayParseError(f"{path}:1: front matter needs 'day' and 'stops'")
    stops = [Stop(name=s["name"], port_id=str(s.get("port_id", ""))) for s in front["stops"]]
    multi = len(stops) > 1
    base = 3 if multi else 2  # level of "About" and "Shore Excursions" headings

    notes = []
    stop_idx = 0
    # Current open section: (kind, title, start_line, lines)
    current = None
    in_excursions = False

    def flush():
        nonlocal current
        if current is None:
            return
        kind, title, start, lines = current
        content = "\n".join(lines).strip()
        stop = stops[stop_idx]
        if kind == "about":
            stop.about_md = content
        elif kind == "excursion":
            facts, desc = _parse_facts(lines)
            if facts.get("Excursion ID"):
                stop.excursions.append(Excursion(
                    id=facts["Excursion ID"].strip(), title=title, facts=facts,
                    description_md=desc, line=start))
            elif content:
                notes.append(Note(title=title, body_md=content, stop=stop.name if multi else ""))
        elif kind == "note" and (content or title):
            notes.append(Note(title=title, body_md=content, stop=stop.name if multi else ""))
        current = None

    for offset, line in enumerate(body.split("\n")):
        lineno = first_line + offset
        m = HEADING.match(line)
        if not m:
            if current is not None:
                current[3].append(line)
            continue
        level, title = len(m.group(1)), m.group(2)
        if level == 1:
            flush()
            in_excursions = False
            continue
        if multi and level == 2:
            flush()
            in_excursions = False
            names = [s.name for s in stops]
            if title in names:
                stop_idx = names.index(title)
            else:
                current = ("note", title, lineno, [])
            continue
        if level == base:
            flush()
            if title.startswith("About "):
                in_excursions = False
                current = ("about", title, lineno, [])
            elif title.startswith("Shore Excursions"):
                in_excursions = True
                current = None
            else:
                in_excursions = False
                current = ("note", title, lineno, [])
            continue
        if level == base + 1 and in_excursions:
            flush()
            current = ("excursion", title, lineno, [])
            continue
        if current is not None and current[0] in ("note", "excursion", "about") and level > base:
            # Sub-heading inside a section: keep it as part of that section's Markdown.
            current[3].append(line)
            continue
        flush()
        in_excursions = False
        current = ("note", title, lineno, [])
    flush()
    return DayDoc(path=path, front=front, stops=stops, notes=notes)
