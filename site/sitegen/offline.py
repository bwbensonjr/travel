"""Service worker and web app manifest generation."""
import json
from pathlib import Path

# Files that must not be precached.
EXCLUDE = {"sw.js", "robots.txt"}

SW_TEMPLATE = """// Generated by site/build.py. Do not edit.
"use strict";
const VERSION = __VERSION__;
const CACHE = "trip-cache-" + VERSION;
const PRECACHE = __PRECACHE__;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(PRECACHE.map((u) => new Request(u, { cache: "reload" }))))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    const old = keys.filter((k) => k.startsWith("trip-cache-") && k !== CACHE);
    await Promise.all(old.map((k) => caches.delete(k)));
    await self.clients.claim();
    const clients = await self.clients.matchAll({ type: "window" });
    clients.forEach((c) => c.postMessage({ type: "activated", version: VERSION, replaced: old.length > 0 }));
  })());
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;  // map tiles, external links: network only
  if (req.mode === "navigate") {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      const hit = await cache.match(req, { ignoreSearch: true });
      if (hit) return hit;
      try {
        return await fetch(req);
      } catch (err) {
        return Response.redirect(new URL("offline/", self.registration.scope).href, 302);
      }
    })());
    return;
  }
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(req);
    return hit || fetch(req);
  })());
});

self.addEventListener("message", (event) => {
  if (!event.data || event.data.type !== "status") return;
  const port = event.ports[0];
  if (!port) return;
  caches.open(CACHE).then(async (cache) => {
    const keys = await cache.keys();
    const have = new Set(keys.map((r) => r.url));
    const missing = PRECACHE.filter((u) => !have.has(new URL(u, self.registration.scope).href));
    port.postMessage({ version: VERSION, complete: missing.length === 0, missing: missing.length });
  });
});
"""


def precache_urls(out_dir):
    """URLs (relative to the site root) for every generated file, pages as directories."""
    out_dir = Path(out_dir)
    urls = []
    for path in sorted(out_dir.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(out_dir).as_posix()
        if rel in EXCLUDE or path.name in (".DS_Store", "VERSION", "LICENSE"):
            continue
        if path.name == "index.html":
            rel = rel[: -len("index.html")] or "./"
        urls.append(rel)
    return urls


def service_worker(urls, version):
    return (SW_TEMPLATE
            .replace("__VERSION__", json.dumps(version))
            .replace("__PRECACHE__", json.dumps(urls, indent=1)))


def manifest(config):
    first = config["trips"][0]
    return json.dumps({
        "name": config["title"],
        "short_name": config.get("short_name", config["title"]),
        "description": first["title"],
        "start_url": f"{first['slug']}/",
        "scope": "./",
        "display": "standalone",
        "background_color": "#f5f6f8",
        "theme_color": "#1d5bc4",
        "icons": [
            {"src": "static/icons/icon-192.png", "sizes": "192x192", "type": "image/png"},
            {"src": "static/icons/icon-512.png", "sizes": "512x512", "type": "image/png"},
            {"src": "static/icons/icon.svg", "sizes": "any", "type": "image/svg+xml"},
        ],
    }, indent=1)
